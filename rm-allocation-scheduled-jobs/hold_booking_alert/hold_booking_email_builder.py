from datetime import datetime
from typing import Any
from typing import List
from .database_models import HoldBookingQueryResult
from zoneinfo import ZoneInfo


class HoldBookingEmailBuilder:
    """
    Builds the email HTML body for hold booking alerts.
    """

    def build(
        self,
        alert_rows: List[HoldBookingQueryResult],
        threshold_percentage: int,
        generated_time_ist: str,
    ) -> str:
        """
        Build email HTML body.

        Returns:
            str -> html_body
        """

        #subject = "Hold Booking Alert"

        table_rows = ""

        for row in alert_rows:
            table_rows += f"""
                <tr>
                    <td style="border:1px solid #000;padding:8px;">
                        {row.inventory_leg_key}
                    </td>
                    <td style="border:1px solid #000;padding:8px;text-align:center;">
                        {row.class_of_service}
                    </td>
                    <td style="border:1px solid #000;padding:8px;text-align:center;">
                        {row.total_booking}
                    </td>
                    <td style="border:1px solid #000;padding:8px;text-align:center;">
                        {row.booking_on_hold}
                    </td>
                    <td style="border:1px solid #000;padding:8px;text-align:center;">
                        {row.booking_on_hold_percentage:.2f}%
                    </td>
                </tr>
            """

        # generated_time = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

        html_body = f"""
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="UTF-8">
        </head>
        <body style="
            font-family: Arial, Helvetica, sans-serif;
            font-size: 14px;
            color: #333333;
        ">

            <h2 style="color:#d9534f;">
                Hold Booking Alert
            </h2>

            <table
                style="
                    border-collapse: collapse;
                    width: 100%;
                    border: 1px solid #000000;
                "
            >
                <thead>
                    <tr style="background-color:#eaeaea;">
                        <th style="
                            border:1px solid #000;
                            padding:10px;
                            font-weight:bold;
                            text-align:left;
                        ">
                            InventoryLegKey
                        </th>

                        <th style="
                            border:1px solid #000;
                            padding:10px;
                            font-weight:bold;
                            text-align:center;
                        ">
                            ClassOfService
                        </th>

                        <th style="
                            border:1px solid #000;
                            padding:10px;
                            font-weight:bold;
                            text-align:center;
                        ">
                            TotalBookings
                        </th>

                        <th style="
                            border:1px solid #000;
                            padding:10px;
                            font-weight:bold;
                            text-align:center;
                        ">
                            BookingsOnHold
                        </th>

                        <th style="
                            border:1px solid #000;
                            padding:10px;
                            font-weight:bold;
                            text-align:center;
                        ">
                            BookingsOnHold_%
                        </th>
                    </tr>
                </thead>

                <tbody>
                    {table_rows}
                </tbody>
            </table>

            <br>

            <p>
                <strong>Alert Threshold:</strong>
                {threshold_percentage}%
            </p>

            <p>
                <strong>Generated At:</strong>
                {generated_time_ist}
            </p>

            <hr>

            <p style="font-size:12px;color:#666666;">
                This is an automated email generated by the Hold Booking Alert System.
                Please do not reply to this message.
            </p>

        </body>
        </html>
        """

        return html_body
