import pytest
from hold_booking_alert.hold_booking_email_builder import HoldBookingEmailBuilder
from hold_booking_alert.database_models import HoldBookingQueryResult


class TestHoldBookingEmailBuilder:

    def test_build_returns_expected_subject_and_body(self):

        rows = [
            HoldBookingQueryResult(
                inventory_leg_key="BOMDEL001",
                class_of_service="Y",
                total_booking=100,
                booking_on_hold=30,
                booking_on_hold_percentage=30.0,
            )
        ]

        builder = HoldBookingEmailBuilder()

        body = builder.build(
            alert_rows=rows,
            threshold_percentage=20,
            generated_time_ist="2026-07-09 09:30:00 IST",
        )

        #assert subject == "Hold Booking Alert"

        assert "BOMDEL001" in body
        assert "Y" in body
        assert "100" in body
        assert "30" in body
        assert "30.00%" in body

        assert "20%" in body

        assert "2026-07-09 09:30:00 IST" in body

        assert "Hold Booking Alert" in body

    @pytest.mark.parametrize("booking_pct", [20.0, 25.5, 45.75])
    def test_build_renders_booking_percentage(self, booking_pct):
        row = HoldBookingQueryResult(
            inventory_leg_key="BOMDEL001",
            class_of_service="Y",
            total_booking=100,
            booking_on_hold=25,
            booking_on_hold_percentage=booking_pct,
        )

        builder = HoldBookingEmailBuilder()

        html_body = builder.build(
            [row], threshold_percentage=20, generated_time_ist="2026-07-09 10:30:00 IST"
        )
        print(html_body)
        assert f"{booking_pct:.2f}%" in html_body

    def test_build_with_empty_rows_should_generate_empty_table(self):
        # Arrange
        builder = HoldBookingEmailBuilder()

        # Act
        html_body = builder.build(
            alert_rows=[],
            threshold_percentage=20,
            generated_time_ist="2026-07-09 10:30:00 IST",
        )

        # Assert
        # assert subject == "Hold Booking Alert"
        assert "<tbody>" in html_body
        assert "</tbody>" in html_body
        assert "20%" in html_body

    def test_build_should_return_subject_and_html_body(self):
        # Arrange
        alert_rows = [
            HoldBookingQueryResult(
                inventory_leg_key="BOMDEL001",
                class_of_service="Y",
                total_booking=100,
                booking_on_hold=25,
                booking_on_hold_percentage=25.0,
            ),
            HoldBookingQueryResult(
                inventory_leg_key="DELBLR001",
                class_of_service="J",
                total_booking=50,
                booking_on_hold=15,
                booking_on_hold_percentage=30.0,
            ),
        ]

        threshold_percentage = 20
        generated_time_ist = "2026-07-09 10:30:00 IST"

        builder = HoldBookingEmailBuilder()

        # Act
        html_body = builder.build(
            alert_rows=alert_rows,
            threshold_percentage=threshold_percentage,
            generated_time_ist=generated_time_ist,
        )

        # Assert
        #assert subject == "Hold Booking Alert"

        # Verify table headers
        assert "InventoryLegKey" in html_body
        assert "ClassOfService" in html_body
        assert "TotalBookings" in html_body
        assert "BookingsOnHold" in html_body
        assert "BookingsOnHold_%" in html_body

        # Verify first row data
        assert "BOMDEL001" in html_body
        assert "Y" in html_body
        assert "100" in html_body
        assert "25" in html_body
        assert "25.00%" in html_body

        # Verify second row data
        assert "DELBLR001" in html_body
        assert "J" in html_body
        assert "50" in html_body
        assert "15" in html_body
        assert "30.00%" in html_body

        # Verify threshold
        assert "20%" in html_body

        # Verify generated timestamp
        assert generated_time_ist in html_body

        # Verify footer text
        assert (
            "This is an automated email generated by the Hold Booking Alert System."
            in html_body
        )
